/** Собирает шаги тура под роли пользователя: приветствие → видимые разделы →
 * уведомления → финал. Состав совпадает с тем, что реально видно в меню. */
export function buildStepsForRoles(roles: Role[]): TourStep[] {
  const visible = NAV.flatMap((g) => g.items).filter(
    (i) => !i.roles || i.roles.some((r) => roles.includes(r)),
  );

  const steps: TourStep[] = [
    {
      title: "Добро пожаловать в «Веху»!",
      body: "Проведём короткую экскурсию по разделам, которые доступны именно вам. Это займёт меньше минуты — нажмите «Далее».",
    },
  ];

  for (const item of visible) {
    steps.push({
      target: item.to,
      title: item.label,
      body: ROUTE_HELP[item.to] ?? `Раздел «${item.label}».`,
    });
  }

  steps.push({
    target: "notifications",
    title: "Уведомления",
    body: "Сюда приходят события: например, когда таймшит отклонён или Заказчик предоставил данные.",
  });
  steps.push({
    title: "Готово!",
    body: "Вы освоились с навигацией. Повторить экскурсию можно в любой момент кнопкой «?» в шапке. Удачной работы!",
  });

  return steps;
}
