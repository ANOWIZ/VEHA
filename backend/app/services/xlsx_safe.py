"""Защита XLSX-экспорта от формульной инъекции (CWE-1236).

openpyxl не экранирует ведущие ``= + - @`` и управляющие символы (Tab/CR/LF):
значение, начатое с них, Excel/LibreOffice при открытии трактует как формулу
(напр. ``=HYPERLINK(...)``/``=WEBSERVICE(...)``). Пользовательский ввод
(комментарии таймшитов, наименования строк ТКП, имена проектов) пишется в ячейки
как есть, поэтому перед записью текстовых значений применяем ``safe_text``.
"""

from __future__ import annotations

_RISKY_PREFIXES = ("=", "+", "-", "@", "\t", "\r", "\n")


def safe_text(value: object) -> object:
    """Для строк, начинающихся с опасного символа, добавляет ведущий апостроф —
    Excel/LibreOffice тогда трактует ячейку как текст, а не формулу. Нестроковые
    значения (числа, None) возвращаются без изменений."""
    if isinstance(value, str) and value and value[0] in _RISKY_PREFIXES:
        return "'" + value
    return value
